
x = 15
y = 20
z = 25


# 1. x ist größer als y
print(x > y)

# 2. x ist größer als y und kleiner als z
print(x > y and x < z)

# 3. x ist durch y teilbar
print(x % y == 0)

# 4. x ist größer als y, oder x ist kleiner als y
print(x != y)

# 5. x ist nicht gleich 0
print(x != 0)
print(bool(x))
print(not x == 0)

# 6. x ist um maximal 5 zum Wert von y unterschiedlich
print(abs(x) < abs(y) + 6)
print(abs(x - y) <= 5)





